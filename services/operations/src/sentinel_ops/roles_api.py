@router.get("/api/fraud/claims")
def browse_claims(
    q: str | None = None,
    peril: str | None = None,
    suburb: str | None = None,
    item_type: str | None = None,
    min_amount: float | None = None,
    sort: Literal["recent", "amount", "suburb"] = "recent",
    limit: int = Query(50, ge=1, le=500),
    offset: int = 0,
):
    """Every claim, filterable. Fraud role only."""
    rows = claims()
    if not rows:
        raise HTTPException(status_code=503, detail=_load_workbook()[1])

    def keep(c):
        if peril and (c["peril"] or "").lower() != peril.lower():
            return False
        if suburb and (c["suburb"] or "").lower() != suburb.lower():
            return False
        if item_type and (c["item_type"] or "").lower() != item_type.lower():
            return False
        if min_amount and c["amount"] < min_amount:
            return False
        if q:
            hay = " ".join(str(c.get(k) or "") for k in
                           ("incident_id", "suburb", "peril", "vehicle_make", "vehicle_model"))
            if q.lower() not in hay.lower():
                return False
        return True

    filtered = [c for c in rows if keep(c)]
    if sort == "amount":
        filtered.sort(key=lambda c: c["amount"], reverse=True)
    elif sort == "suburb":
        filtered.sort(key=lambda c: (c["suburb"] or "", -c["amount"]))
    else:
        filtered.sort(key=lambda c: c["incident_at"] or "", reverse=True)

    return {
        "total": len(filtered),
        "offset": offset,
        "limit": limit,
        "value": round(sum(c["amount"] for c in filtered), 2),
        "claims": filtered[offset: offset + limit],
        "facets": {
            "perils": dict(Counter(c["peril"] for c in filtered).most_common(8)),
            "item_types": dict(Counter(c["item_type"] for c in filtered).most_common()),
        },
    }


@router.get("/api/fraud/claims/{incident_id}/report")
def claim_report(incident_id: str):
    """An analytical report on one claim.

    Every figure here is computed from the workbook and can be traced back to rows an
    investigator can pull. Findings are graded INFO / WATCH / FLAG. A FLAG is a reason
    to look closer — it is explicitly not an accusation, and the response says so.
    """
    rows = claims()
    claim = next((c for c in rows if c["incident_id"] == incident_id), None)
    if not claim:
        raise HTTPException(status_code=404, detail=f"unknown claim {incident_id}")

    stats = _suburb_stats().get(claim["suburb"] or "", None)
    findings: list[dict[str, str]] = []
    when = datetime.fromisoformat(claim["incident_at"]) if claim["incident_at"] else None

    # --- sample size first: a percentile from three rows means nothing ---
    if stats and stats["count"] < 10:
        findings.append({
            "level": "WATCH", "code": "SMALL_SAMPLE",
            "title": f"Only {stats['count']} claim(s) on record for {claim['suburb']}",
            "detail": "The comparisons below rest on a very small sample, so percentiles and "
                      "medians for this suburb are not meaningful. Compare against the peril "
                      "or item type nationally instead.",
        })

    # --- amount vs the suburb's own distribution ---
    pct = None
    if stats and stats["amounts"]:
        pct = _percentile(stats["amounts"], claim["amount"])
        ratio = claim["amount"] / stats["median"] if stats["median"] else 0
        if pct >= 99:
            findings.append({
                "level": "FLAG", "code": "AMOUNT_EXTREME",
                "title": f"Amount sits in the top 1% for {claim['suburb']}",
                "detail": f"R{claim['amount']:,.0f} against a suburb median of "
                          f"R{stats['median']:,.0f} ({ratio:.1f}x). High-value claims are "
                          f"legitimate every day — this only means the file deserves a second reader.",
            })
        elif pct >= 90:
            findings.append({
                "level": "WATCH", "code": "AMOUNT_HIGH",
                "title": f"Amount is in the {pct:.0f}th percentile for {claim['suburb']}",
                "detail": f"R{claim['amount']:,.0f} vs median R{stats['median']:,.0f}.",
            })
        else:
            findings.append({
                "level": "INFO", "code": "AMOUNT_TYPICAL",
                "title": f"Amount is typical for {claim['suburb']} ({pct:.0f}th percentile)",
                "detail": f"R{claim['amount']:,.0f} vs median R{stats['median']:,.0f}.",
            })

    # --- national context, which is always well-populated ---
    peer = [c["amount"] for c in rows
            if c["item_type"] == claim["item_type"] and c["peril"] == claim["peril"]]
    if peer:
        peer.sort()
        npct = _percentile(peer, claim["amount"])
        findings.append({
            "level": "FLAG" if npct >= 99.5 else "WATCH" if npct >= 97 else "INFO",
            "code": "AMOUNT_NATIONAL",
            "title": f"{npct:.1f}th percentile against all {len(peer):,} "
                     f"{claim['peril']} / {claim['item_type']} claims",
            "detail": f"R{claim['amount']:,.0f} against a national median of "
                      f"R{statistics.median(peer):,.0f} for this peril and item type. "
                      f"This comparison uses the whole book, so it holds even where the "
                      f"suburb sample is thin.",
        })

    # --- timestamp quality ---
    if when and when.hour == 0 and when.minute == 0:
        midnight = sum(1 for c in rows
                       if c["incident_at"] and c["incident_at"].endswith("T00:00:00"))
        findings.append({
            "level": "WATCH", "code": "TIME_MIDNIGHT",
            "title": "Incident time recorded as exactly midnight",
            "detail": f"{midnight:,} claims in the book share this timestamp, so it usually means "
                      f"the time was unknown at capture rather than anything suspicious. "
                      f"Camera retrieval for this claim cannot rely on the hour.",
        })
    elif when and stats:
        if when.hour in stats["peak_hours"]:
            findings.append({
                "level": "INFO", "code": "TIME_PEAK",
                "title": f"Occurred inside {claim['suburb']}'s peak risk window",
                "detail": f"{when.strftime('%H:%M on %A')} — this suburb's busiest hours are "
                          f"{', '.join(f'{h:02d}:00' for h in stats['peak_hours'])}.",
            })
        else:
            findings.append({
                "level": "INFO", "code": "TIME_OFFPEAK",
                "title": "Occurred outside the suburb's usual pattern",
                "detail": f"{when.strftime('%H:%M on %A')}; peak hours here are "
                          f"{', '.join(f'{h:02d}:00' for h in stats['peak_hours'])}.",
            })

    # --- nearby claims in a tight window (cluster or spree) ---
    cluster = []
    if when and claim["suburb"]:
        for c in rows:
            if c["incident_id"] == incident_id or c["suburb"] != claim["suburb"] or not c["incident_at"]:
                continue
            if abs((datetime.fromisoformat(c["incident_at"]) - when).total_seconds()) <= 72 * 3600:
                cluster.append(c)
    if len(cluster) >= 3:
        findings.append({
            "level": "FLAG", "code": "CLUSTER",
            "title": f"{len(cluster)} other claims in {claim['suburb']} within 72 hours",
            "detail": "A tight cluster usually means a spree rather than anything about this "
                      "claimant. It is the strongest argument for pulling camera evidence "
                      "across the whole window, not just this address.",
        })
    elif cluster:
        findings.append({
            "level": "INFO", "code": "CLUSTER_LIGHT",
            "title": f"{len(cluster)} other claim(s) nearby within 72 hours",
            "detail": "Worth cross-referencing when retrieving evidence.",
        })

    # --- vehicle context ---
    if claim["vehicle_make"]:
        make_rows = [c for c in rows if c["vehicle_make"] == claim["vehicle_make"]]
        rank = sorted(Counter(c["vehicle_make"] for c in rows if c["vehicle_make"]).items(),
                      key=lambda kv: -kv[1])
        pos = next((i + 1 for i, (m, _) in enumerate(rank) if m == claim["vehicle_make"]), None)
        findings.append({
            "level": "INFO", "code": "VEHICLE_CONTEXT",
            "title": f"{claim['vehicle_make']} is #{pos} most-claimed make in the book",
            "detail": f"{len(make_rows):,} claims involve this make. "
                      f"Model on file: {claim['vehicle_model'] or 'not recorded'}.",
        })

    # --- camera coverage at the time of the incident ---
    coverage = _coverage_for(claim["suburb"])
    if coverage["cameras"]:
        findings.append({
            "level": "INFO", "code": "COVERAGE",
            "title": f"{len(coverage['cameras'])} participating camera(s) in {claim['suburb']}",
            "detail": "Incident Time Machine can reconstruct the window around this claim.",
        })
    else:
        findings.append({
            "level": "WATCH", "code": "NO_COVERAGE",
            "title": f"No participating cameras in {claim['suburb']}",
            "detail": "No camera evidence can be retrieved for this claim. This is exactly the "
                      "gap the Coverage Optimizer is meant to close.",
        })

    flags = sum(1 for f in findings if f["level"] == "FLAG")
    watches = sum(1 for f in findings if f["level"] == "WATCH")
    if flags >= 2:
        rec, priority = "Refer for investigator review before settlement.", "HIGH"
    elif flags == 1:
        rec, priority = "Pull camera evidence for the incident window, then reassess.", "MEDIUM"
    elif watches:
        rec, priority = "Proceed, noting the data-quality caveats above.", "LOW"
    else:
        rec, priority = "Nothing anomalous found. Proceed on normal terms.", "ROUTINE"

    return {
        "claim": claim,
        "context": {
            "suburb_incidents_5y": stats["count"] if stats else 0,
            "suburb_total_value": round(stats["total"], 2) if stats else 0,
            "suburb_median": round(stats["median"], 2) if stats else 0,
            "amount_percentile": pct,
            "peak_hours": stats["peak_hours"] if stats else [],
            "peak_days": stats["peak_days"] if stats else [],
        },
        "coverage": coverage,
        "cluster": sorted(cluster, key=lambda c: c["incident_at"] or "")[:12],
        "findings": findings,
        "assessment": {
            "priority": priority,
            "recommendation": rec,
            "flags": flags,
            "watches": watches,
        },
        "disclaimer": "Findings are statistical context computed from the supplied claims "
                      "workbook. They indicate where a human should look, not whether a claim "
                      "is fraudulent. No claim is declined on the basis of this report.",
    }


def _coverage_for(suburb: str | None) -> dict[str, Any]:
    if not suburb:
        return {"suburb": None, "cameras": []}
    try:
        from sentinel_ops.camera_upload import CAMERA_ROSTER
        roster = list(CAMERA_ROSTER)
    except Exception:
        roster = []
    roster += _member_cameras
    cams = [c for c in roster if (c.get("suburb") or "").lower() == suburb.lower()]
    return {"suburb": suburb, "cameras": [
        {"camera_id": c["camera_id"], "household": c.get("household"),
         "latitude": c.get("latitude"), "longitude": c.get("longitude")} for c in cams]}


# --------------------------------------------------------------- MOVEMENT TRAILS
@router.get("/api/fraud/movement")
def movement_trails(days: int = Query(30, ge=1, le=365), min_sightings: int = 2):
    """Reconstructed movement across cameras — the 'activity trail' view.

    Each confirmed or candidate pattern becomes a trail: its sightings ordered in
    time, joined into a path between camera positions. Segments travelled by more
    than one pattern accumulate weight, which is what makes the aggregate heat layer.

    This shows where *evidence* recurs, not where people go. Only patterns the system
    already surfaced appear here, and none of them carries an identity.
    """
    try:
        from sentinel_ops.patterns_api import registry
        reg = registry()
        patterns = reg.store.list_patterns()
    except Exception as exc:
        raise HTTPException(status_code=503, detail=f"pattern registry unavailable: {exc}")

    try:
        from sentinel_ops.camera_upload import CAMERA_ROSTER
        positions = {c["camera_id"]: (c["latitude"], c["longitude"], c.get("suburb"))
                     for c in list(CAMERA_ROSTER) + _member_cameras}
    except Exception:
        positions = {}

    cutoff = datetime.now().astimezone() - timedelta(days=days)
    trails, segments = [], Counter()

    for p in patterns:
        if p.occurrence_count < min_sightings:
            continue
        pts = []
        for cam_id in p.camera_ids:
            if cam_id in positions:
                lat, lon, sub = positions[cam_id]
                pts.append({"camera_id": cam_id, "suburb": sub, "latitude": lat, "longitude": lon})
        if len(pts) < 2:
            continue
        dist = 0.0
        for a, b in zip(pts, pts[1:]):
            dist += _haversine(a["latitude"], a["longitude"], b["latitude"], b["longitude"])
            key = tuple(sorted([a["camera_id"], b["camera_id"]]))
            segments[key] += 1
        trails.append({
            "pattern_id": p.pattern_id,
            "kind": p.kind,
            "status": p.status,
            "description": p.describe(),
            "sightings": p.occurrence_count,
            "distance_km": round(dist, 2),
            "first_seen": p.first_seen,
            "last_seen": p.last_seen,
            "points": pts,
        })

    corridors = []
    for (a, b), weight in segments.most_common():
        if a in positions and b in positions:
            corridors.append({
                "from": a, "to": b, "weight": weight,
                "from_point": {"latitude": positions[a][0], "longitude": positions[a][1]},
                "to_point": {"latitude": positions[b][0], "longitude": positions[b][1]},
            })

    hot = Counter()
    for t in trails:
        for pt in t["points"]:
            hot[(pt["camera_id"], pt["latitude"], pt["longitude"], pt["suburb"])] += 1

    return {
        "window_days": days,
        "trail_count": len(trails),
        "trails": sorted(trails, key=lambda t: -t["sightings"]),
        "corridors": corridors,
        "nodes": [{"camera_id": c, "latitude": la, "longitude": lo, "suburb": s, "weight": w}
                  for (c, la, lo, s), w in hot.most_common()],
        "note": "Trails are reconstructed from evidence patterns, not from tracking "
                "individuals. Nothing here is attributed to a named person.",
    }


def _haversine(lat1, lon1, lat2, lon2) -> float:
    R = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = math.radians(lat2 - lat1), math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * R * math.asin(math.sqrt(a))


