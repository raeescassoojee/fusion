@router.get("/api/security/briefing")
def security_briefing(metro: str = "Gauteng", shift: Literal["day", "night"] = "night"):
    """Operational briefing for a partner response company.

    Deliberately excludes claim amounts, member identities and raw evidence. A
    security partner needs to know where to be and when — not what anyone lost or
    who they are.
    """
    try:
        hotspots, meta = load_claims_hotspots(metro)
    except Exception as exc:
        raise HTTPException(status_code=503, detail=str(exc))

    ranked = sorted(hotspots, key=lambda h: -(getattr(h, "operational_priority", 0) or 0))
    stats = _suburb_stats()
    items = []
    for h in ranked:
        s = stats.get(h.name, {})
        hours = s.get("peak_hours", [])
        night = [x for x in hours if x >= 18 or x <= 5]
        day = [x for x in hours if 6 <= x <= 17]
        relevant = night if shift == "night" else day
        pw = getattr(h, "peak_window", None)
        items.append({
            "hotspot_id": h.hotspot_id,
            "area": h.name,
            "priority": round(float(getattr(h, "operational_priority", 0) or 0), 1),
            "band": "HIGH" if (getattr(h, "operational_priority", 0) or 0) >= 60
                    else "MEDIUM" if (getattr(h, "operational_priority", 0) or 0) >= 40 else "LOW",
            "dominant_peril": getattr(h, "main_peril", None),
            "incidents_5y": s.get("count"),
            "peak_hours_all": hours,
            "peak_hours_this_shift": relevant,
            "peak_days": s.get("peak_days", []),
            "geofence_radius_km": getattr(h, "geofence_radius_km", None),
            "location": {"latitude": h.location.latitude, "longitude": h.location.longitude}
                        if getattr(h, "location", None) else None,
            "recommended_presence": (
                "sustained patrol through the risk window" if (getattr(h, "operational_priority", 0) or 0) >= 60
                else "scheduled passes at peak hours" if (getattr(h, "operational_priority", 0) or 0) >= 40
                else "routine coverage"),
        })

    coverage_gaps = []
    for it in items:
        cams = _coverage_for(it["area"])["cameras"]
        if it["band"] in ("HIGH", "MEDIUM") and not cams:
            coverage_gaps.append({
                "area": it["area"], "priority": it["priority"],
                "reason": "high risk with no participating camera — evidence cannot be retrieved here",
            })

    return {
        "metro": metro,
        "shift": shift,
        "generated_at": datetime.now().astimezone().isoformat(),
        "hotspots": items,
        "focus": [i["area"] for i in items[:3]],
        "coverage_gaps": coverage_gaps,
        "excluded": ["claim amounts", "member identities", "raw camera evidence"],
        "note": "Priority scores are derived from Discovery claims history fused with "
                "SAPS context. They rank where attention is worth spending; they are not "
                "predictions that a crime will occur.",
    }


class SiteProposal(BaseModel):
    area: str
    latitude: float
    longitude: float
    reason: str = "partner-nominated coverage point"


@router.post("/api/security/sites")
def propose_site(body: SiteProposal, metro: str = "Gauteng"):
    """A security partner nominates an extra location to fold into route planning."""
    try:
        hotspots, _ = load_claims_hotspots(metro)
    except Exception as exc:
        raise HTTPException(status_code=503, detail=str(exc))
    nearest, best = None, 1e9
    for h in hotspots:
        if not getattr(h, "location", None):
            continue
        d = _haversine(body.latitude, body.longitude, h.location.latitude, h.location.longitude)
        if d < best:
            nearest, best = h, d
    site = {
        "site_id": "SITE-" + str(abs(hash((body.area, round(body.latitude, 4)))) % 100000).zfill(5),
        "area": body.area, "latitude": body.latitude, "longitude": body.longitude,
        "reason": body.reason,
        "nearest_hotspot": nearest.hotspot_id if nearest else None,
        "nearest_hotspot_name": nearest.name if nearest else None,
        "distance_km": round(best, 2) if nearest else None,
        "inherits_priority": round(float(getattr(nearest, "operational_priority", 0) or 0), 1)
                             if nearest and best <= 3 else None,
    }
    _security_sites.append(site)
    return {
        "site": site,
        "note": "Nominated sites join route planning at the priority of the hotspot they "
                "fall inside. Beyond 3 km they carry no inherited risk weight — the claims "
                "data has nothing to say about them.",
    }


