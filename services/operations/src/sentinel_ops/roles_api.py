@router.on_event("startup")
async def _warm_cache() -> None:
    """Read the workbook once at boot.

    Parsing 15k rows takes several seconds. Doing it lazily means the first
    investigator to open the claims browser waits — and in a demo that pause reads
    as a hang. Warming here moves the cost to startup where nobody is watching.
    """
    import asyncio

    def load():
        rows, src = _load_workbook()
        if rows:
            _suburb_stats()
        return len(rows), src

    try:
        count, src = await asyncio.get_event_loop().run_in_executor(None, load)
        print(f"[roles] claims workbook ready: {count:,} rows from {src}")
    except Exception as exc:  # never block startup on this
        print(f"[roles] workbook warm-up skipped: {exc}")


