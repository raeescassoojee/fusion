# --------------------------------------------------------------------- workbook
@lru_cache(maxsize=1)
def _load_workbook() -> tuple[list[dict[str, Any]], str]:
    """Read the claims workbook once and cache it."""
    try:
        import pandas as pd
    except ImportError:
        return [], "pandas not installed"

    for base in WORKBOOK_CANDIDATES:
        if not base.exists():
            continue
        for path in sorted(base.glob("*.xlsx")):
            try:
                df = pd.read_excel(path)
            except Exception:
                continue
            if "CLAIM_AMOUNT" not in df.columns:
                continue
            def clean(v):
                """pandas leaves NaN in float columns even after .where(notna) — strip it here."""
                if v is None:
                    return None
                if isinstance(v, float) and math.isnan(v):
                    return None
                return v

            rows = []
            for i, r in enumerate(df.to_dict("records"), 1):
                r = {k: clean(v) for k, v in r.items()}
                dt = r.get("INCIDENT_DATE_TIME")
                suburb = r.get("SUBURB")
                year = r.get("VEHICLE_YEAR")
                rows.append({
                    "incident_id": r.get("Incident") or f"INC-{i:05d}",
                    "peril": r.get("PERIL"),
                    "suburb": str(suburb).strip().title() if suburb else None,
                    "item_type": r.get("ITEM_TYPE"),
                    "item_category": r.get("ITEM_CATEGORY"),
                    "peril_descr": r.get("ITEM_PERIL_DESCR"),
                    "vehicle_make": r.get("VEHICLE_MAKE"),
                    "vehicle_model": r.get("VEHICLE_MODEL"),
                    "vehicle_year": int(year) if year else None,
                    "incident_at": dt.isoformat() if hasattr(dt, "isoformat") else None,
                    "amount": float(r.get("CLAIM_AMOUNT") or 0),
                })
            return rows, str(path)
    return [], "workbook not found"


def claims() -> list[dict[str, Any]]:
    return _load_workbook()[0]


@lru_cache(maxsize=1)
def _suburb_stats() -> dict[str, dict[str, Any]]:
    """Per-suburb distribution, so a single claim can be placed in context."""
    by: dict[str, list[dict]] = defaultdict(list)
    for c in claims():
        if c["suburb"]:
            by[c["suburb"]].append(c)
    out = {}
    for suburb, rows in by.items():
        amounts = sorted(r["amount"] for r in rows)
        hours = [datetime.fromisoformat(r["incident_at"]).hour for r in rows if r["incident_at"]]
        days = [datetime.fromisoformat(r["incident_at"]).strftime("%A") for r in rows if r["incident_at"]]
        out[suburb] = {
            "count": len(rows),
            "total": sum(amounts),
            "median": statistics.median(amounts) if amounts else 0,
            "p90": amounts[int(len(amounts) * 0.9)] if amounts else 0,
            "amounts": amounts,
            "peak_hours": [h for h, _ in Counter(hours).most_common(3)],
            "peak_days": [d for d, _ in Counter(days).most_common(2)],
            "perils": dict(Counter(r["peril"] for r in rows).most_common(4)),
        }
    return out


def _percentile(sorted_vals: list[float], v: float) -> float:
    if not sorted_vals:
        return 0.0
    lo, hi = 0, len(sorted_vals)
    while lo < hi:
        mid = (lo + hi) // 2
        if sorted_vals[mid] < v:
            lo = mid + 1
        else:
            hi = mid
    return round(100 * lo / len(sorted_vals), 1)


