"""Role-scoped endpoints.

Three audiences, three very different needs:

  MEMBER    a resident with a doorbell camera. Sees their own property, their own
            devices, their own claims. Nothing else — a member must never be able to
            enumerate other households.

  FRAUD     Discovery's claims investigators. Sees every claim, opens one, and gets
            an analytical report placing it against five years of history, plus the
            movement trails that camera evidence reconstructs.

  SECURITY  a partner response company. Sees hotspot briefings and route economics
            for the areas it covers. Never sees claim amounts, member identities, or
            raw evidence — it gets where to go and when, not who.

The claim report is *computed*, not generated by a language model. Every number in
it can be traced back to a row in the workbook, which matters when an investigator
has to defend a decision. Where a narrative layer would help, the endpoint returns
structured findings the caller can render or summarise.
"""
