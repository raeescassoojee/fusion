class CameraRegistration(BaseModel):
    household: str = Field(..., min_length=3, description="street address of the property")
    suburb: str
    metro: str = "Gauteng"
    latitude: float
    longitude: float
    device_label: str = "Doorbell camera"
    consent_acknowledged: bool = Field(
        ..., description="the member confirms every adult at the property has agreed"
    )


_member_cameras: list[dict[str, Any]] = []


@router.post("/api/member/cameras")
def register_camera(body: CameraRegistration):
    """A member adds their own doorbell camera to the mesh.

    Consent is a hard gate, not a checkbox we log and ignore. A camera pointed at a
    shared street records people who never agreed to anything, so the member has to
    affirm the household consented before the device is accepted.
    """
    if not body.consent_acknowledged:
        raise HTTPException(
            status_code=422,
            detail="consent_acknowledged must be true — a camera cannot join the mesh "
                   "without the household confirming agreement",
        )
    if not (-35 < body.latitude < -22 and 16 < body.longitude < 33):
        raise HTTPException(status_code=422, detail="coordinates fall outside South Africa")

    seq = len(_member_cameras) + 1
    prefix = "".join(w[0] for w in body.suburb.split()[:3]).upper()[:3] or "MEM"
    cam = {
        "camera_id": f"CAM-{prefix}-{seq:02d}",
        "household": body.household,
        "suburb": body.suburb.strip().title(),
        "metro": body.metro,
        "latitude": body.latitude,
        "longitude": body.longitude,
        "device_label": body.device_label,
        "status": "PENDING_ACTIVATION",
        "mode": "NORMAL",
        "owner": "member",
        "registered_at": datetime.now().astimezone().isoformat(),
    }
    # Inherit the mode implied by the geofence it lands in.
    try:
        hotspots, _ = load_claims_hotspots(body.metro)
        for h in hotspots:
            if h.name.strip().lower() == cam["suburb"].lower():
                risk = getattr(h, "operational_priority", 0) or 0
                cam["hotspot_id"] = h.hotspot_id
                cam["geofence_risk"] = round(float(risk), 1)
                cam["mode"] = "HEIGHTENED" if float(risk) >= 60 else "NORMAL"
                break
    except Exception:
        pass
    _member_cameras.append(cam)
    return {
        "camera": cam,
        "next_steps": [
            "Pair the device using the activation code sent to the member.",
            "Point the camera at your own entrance, not a neighbour's property.",
            "Routine video stays on the device — only event crops are uploaded.",
        ],
    }


@router.get("/api/member/cameras")
def member_cameras():
    return {"count": len(_member_cameras), "cameras": _member_cameras}


@router.get("/api/member/summary")
def member_summary(suburb: str = Query(..., description="the member's suburb")):
    """What a resident is allowed to see: their own area, never other households."""
    stats = _suburb_stats().get(suburb.strip().title())
    mine = [c for c in _member_cameras if c["suburb"].lower() == suburb.strip().lower()]
    if not stats:
        return {
            "suburb": suburb,
            "known": False,
            "message": "No claims history for this suburb in the supplied data.",
            "cameras": mine,
        }
    return {
        "suburb": suburb.strip().title(),
        "known": True,
        "incidents_5y": stats["count"],
        "peak_hours": stats["peak_hours"],
        "peak_days": stats["peak_days"],
        "common_perils": stats["perils"],
        "cameras": mine,
        "privacy_note": "Members see area-level patterns only. Individual claims, "
                        "amounts and other households are not exposed to this role.",
    }


